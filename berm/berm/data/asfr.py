def asfr_to_tfr(asfr: tuple[float, ...]) -> float:
    """Convert ASFR (per 1000) tuple to TFR. TFR = 5 * sum(ASFR) / 1000."""
    return 5.0 * sum(asfr) / 1000.0


def get_asfr(country: str, year: int) -> tuple[float, ...] | None:
    """Get ASFR for a country-year, interpolating between available years."""
    data = WPP_ASFR.get(country)
    if data is None:
        return None

    if year in data:
        return data[year]

    years = sorted(data.keys())
    if year <= years[0]:
        return data[years[0]]
    if year >= years[-1]:
        return data[years[-1]]

    for i in range(len(years) - 1):
        if years[i] <= year <= years[i + 1]:
            y0, y1 = years[i], years[i + 1]
            t = (year - y0) / (y1 - y0)
            a0, a1 = data[y0], data[y1]
            return tuple(
                a0[j] + t * (a1[j] - a0[j]) for j in range(len(a0))
            )
    return None


def age_group_midpoint(group: str) -> float:
    """Return midpoint age of a 5-year group (e.g. '25-29' -> 27)."""
    lo, hi = group.split("-")
    return (int(lo) + int(hi)) / 2.0


def mean_age_at_birth(asfr: tuple[float, ...]) -> float:
    """Compute mean age at childbearing from ASFR distribution."""
    total = sum(asfr)
    if total == 0:
        return 28.0
    weighted = sum(
        asfr[i] * age_group_midpoint(AGE_GROUPS[i])
        for i in range(len(AGE_GROUPS))
    )
    return weighted / total
